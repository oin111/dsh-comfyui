export type Lang = 'ru' | 'en'
export const LANGS: readonly Lang[] = ['ru', 'en']
const LANG_KEY = 'dsh-comfyui.lang'

/** Current plugin UI language, read from localStorage (default Russian). */
export function getLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY)
    if (stored === 'en') return 'en'
    if (stored === 'zh') localStorage.setItem(LANG_KEY, 'ru')
    return 'ru'
  } catch {
    return 'ru'
  }
}

/** Persist the plugin UI language choice. */
export function setLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch {
    // storage unavailable (e.g. private mode): the choice just does not persist
  }
}

const DICTS: Record<Lang, Record<string, string>> = { ru, en }

/** Build a plugin-local translator for one language. Resolves {name}
 * placeholders from the first rest argument (same contract as the DSH
 * locale bind), falling back to the key itself when untranslated. */
export function makeT(lang: Lang): (key: string, ...rest: unknown[]) => string {
  const dict = DICTS[lang]
  return (key, ...rest) => {
    const template = dict[key] ?? key
    const params = (rest[0] ?? {}) as Record<string, unknown>
    if (params !== null && typeof params === 'object') {
      return template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = params[name]
        return value === undefined ? match : String(value)
      })
    }
    return template
  }
}
